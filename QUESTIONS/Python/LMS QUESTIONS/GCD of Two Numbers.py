# 1. GCD of Two Numbers
# Given two positive integers A and B, compute their greatest common divisor (GCD) 
# using the Euclidean algorithm.
#
# Input Format:
# A single line containing two positive integers A and B, separated by a space.
#
# Output Format:
# Print a single integer representing gcd(A, B).
#
# Constraints:
# 1 <= A, B <= 10^9
#
# Example 1:
# Input: 48 18
# Output: 6
#
# Example 2:
# Input: 17 5
# Output: 1



